        if (read(strings).trim().isEmpty) {
          emptyLabels.add('$locale:$key');
        }
      }
      for (final (key, format) in _formattedLabels) {
        for (final value in format(strings)) {
          if (value.trim().isEmpty || value.contains('Closure')) {
            emptyLabels.add('$locale:$key');
          }
        }
      }
    }

    expect(emptyLabels, isEmpty, reason: emptyLabels.take(20).join(', '));
  });
